import type { Landmass, MountainZone, Point } from '../types';

export const MAP_WIDTH = 1000;
export const MAP_HEIGHT = 760;

/** A deliberately simplified, hand-drawn game map. Not for navigation. */
export function toMapPoint(longitude: number, latitude: number): Point {
  return {
    x: ((longitude - 122) / 26) * MAP_WIDTH,
    y: ((47 - latitude) / 23) * MAP_HEIGHT,
  };
}

type LonLat = readonly [number, number];
const outline = (coordinates: readonly LonLat[]): Point[] =>
  coordinates.map(([longitude, latitude]) => toMapPoint(longitude, latitude));

